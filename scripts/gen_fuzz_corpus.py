#!/usr/bin/env python3
"""Writes or checks src/test/fuzz_corpus.c3, the list of every hex frame fixture of the test suite that the fuzz tests mutate.

usage: gen_fuzz_corpus.py           rewrite src/test/fuzz_corpus.c3
       gen_fuzz_corpus.py --check   exit 1 if the file does not list exactly the fixtures that exist (no write)

A fixture is a line `const String FX_NAME = "hex bytes";` (or FXP_NAME) in a file of src/test. Standard library only.
"""
import glob
import os
import re
import sys

ROOT = os.environ.get("S7_REPO_ROOT") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TESTS = os.path.join(ROOT, "src", "test")
TARGET = os.path.join(TESTS, "fuzz_corpus.c3")


def fixture_names():
    names = set()
    for path in sorted(glob.glob(os.path.join(TESTS, "*.c3"))):
        if os.path.abspath(path) == os.path.abspath(TARGET):
            continue
        with open(path, encoding="utf-8") as f:
            for m in re.finditer(r'^const String (FXP?_[A-Za-z0-9_]+) = "[0-9A-Fa-f ]+";', f.read(), re.M):
                names.add(m.group(1))
    return sorted(names)


def render(names):
    out = [
        "module s7;",
        "",
        "// Every hex frame fixture of the test suite (valid and malformed), the corpus the fuzz tests mutate.",
        "// Generated by scripts/gen_fuzz_corpus.py; `gen_fuzz_corpus.py --check` fails when it is out of date.",
        "",
        "const String[%d] FUZZ_CORPUS = {" % len(names),
    ]
    out += ["\t%s," % n for n in names]
    out.append("};")
    return "\n".join(out) + "\n"


def main(argv):
    text = render(fixture_names())
    if len(argv) == 2 and argv[1] == "--check":
        with open(TARGET, encoding="utf-8") as f:
            current = f.read()
        if current != text:
            print("src/test/fuzz_corpus.c3 is out of date: run scripts/gen_fuzz_corpus.py")
            return 1
        print("ok")
        return 0
    if len(argv) != 1:
        print(__doc__)
        return 2
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
